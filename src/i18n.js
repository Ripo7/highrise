export const STRINGS = { en: EN, fr: FR };

function detect() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (LANGS.includes(saved)) return saved;
  } catch {
    /* no storage */
  }
  const nav = (typeof navigator !== 'undefined' && (navigator.languages?.[0] || navigator.language)) || 'en';
  return nav.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

let lang = typeof window === 'undefined' ? 'en' : detect();
const listeners = [];

export const getLang = () => lang;

// add strings (the tutorial's) to both languages
export function extend(more) {
  for (const l of LANGS) Object.assign(STRINGS[l], more[l] || {});
}

export function t(key, vars) {
  let s = STRINGS[lang][key] ?? EN[key] ?? key;
  if (vars) {
    s = s.replace(/\{(\w+)\|([^|}]*)\|([^}]*)\}/g, (_, k, one, many) => (Math.abs(+vars[k]) === 1 || (lang === 'fr' && Math.abs(+vars[k]) < 2) ? one : many));
    s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] === undefined ? '' : typeof vars[k] === 'number' ? num(vars[k]) : vars[k]));
  }
  return s;
}

// a number as the language writes it: 1.5 / 1,5, and 1,200 / 1 200
const formats = new Map();
export function num(v, digits = null) {
  const key = `${lang}:${digits}`;
  let f = formats.get(key);
  if (!f) {
    const opts = digits === null ? { maximumFractionDigits: 2 } : { minimumFractionDigits: digits, maximumFractionDigits: digits };
    f = new Intl.NumberFormat(lang === 'fr' ? 'fr-FR' : 'en-US', opts);
    formats.set(key, f);
  }
  return f.format(v);
}

// the HUD's quick one: v.toFixed(d) with the language's decimal mark (no grouping)
export const dec = (v, d = 1) => (lang === 'fr' ? v.toFixed(d).replace('.', ',') : v.toFixed(d));

/**
 * Put the page's own text in the language:
 *   data-i18n="key"          its text
 *   data-i18n-title="key"    its title
 *   data-i18n-aria="key"     its aria-label
 *   data-i18n-attr="a:key"   any attribute (several: "a:key;b:key")
 */
export function applyDom(root = typeof document === 'undefined' ? null : document) {
  if (!root) return;
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    for (const pair of el.dataset.i18nAttr.split(';')) {
      const [a, k] = pair.split(':');
      if (a && k) el.setAttribute(a.trim(), t(k.trim()));
    }
  });
}

export function setLang(l) {
  if (!LANGS.includes(l) || l === lang) return;
  lang = l;
  try {
    localStorage.setItem(LANG_KEY, l);
  } catch {
    /* no storage: this session only */
  }
  applyDom();
  for (const f of listeners) f(l);
}

// re-render what isn't plain page text when the language changes
export const onLang = (f) => listeners.push(f);
